import fs from 'node:fs'
import path from 'node:path'

import micromatch from 'micromatch'
import { Piscina } from 'piscina'

export const DEFAULT_OUT_FILE_PATH = './src/generated/nest-component-scan.ts'
export const DEFAULT_IMPORT_EXTENSION = '.js'

const WORKER_MAIN_FILE_PATH = path.resolve(
  import.meta.dirname,
  './worker/main.js',
)

export type Paths = string | string[]
export type Ignores = string | string[]

export function isIgnored(currentPath: string, ignores: Ignores): boolean {
  return micromatch.isMatch(currentPath, ignores)
}

export type ImportExtension = string | null

export interface ScanOptions {
  signal: AbortSignal
  paths: Paths
  ignores?: Ignores
  outFilePath?: string
  importExtension?: ImportExtension
}

export interface FilledScanOptions {
  signal: AbortSignal
  paths: string[]
  ignores: string[]
  outFilePath: string
  importExtension: ImportExtension
}

export function fillScanOptions(options: ScanOptions): FilledScanOptions {
  return {
    signal: options.signal,
    paths: Array.isArray(options.paths) ? options.paths : [options.paths],
    ignores: Array.isArray(options.ignores)
      ? options.ignores
      : options.ignores
        ? [options.ignores]
        : [],
    outFilePath: options.outFilePath ?? DEFAULT_OUT_FILE_PATH,
    importExtension: options.importExtension ?? DEFAULT_IMPORT_EXTENSION,
  }
}

export async function ensureOutDirPath(outFilePath: string): Promise<string> {
  const outDirPath = path.dirname(outFilePath)

  await fs.promises.mkdir(outDirPath, { recursive: true })

  return outDirPath
}

export interface WorkerInput {
  sourceFilePath: string
  outDirPath: string
  importExtension: ImportExtension
}

export type ComponentKind = 'controller' | 'injectable'

export interface ComponentInfo {
  kind: ComponentKind
  name: string
  importLine: string
}

export type WorkerOutput = ComponentInfo[]

export function createWorkerPool(): Piscina<WorkerInput, WorkerOutput> {
  return new Piscina<WorkerInput, WorkerOutput>({
    filename: WORKER_MAIN_FILE_PATH,
  })
}

export function createFileContents(input: {
  componentInfos: ComponentInfo[]
}): string {
  const { componentInfos } = input

  const importLines = componentInfos.map((x) => x.importLine)
  importLines.sort()

  const controllerLines = componentInfos
    .filter((x) => x.kind === 'controller')
    .map((x) => `  ${x.name},`)
  controllerLines.sort((a, b) => a.localeCompare(b))

  const injectableLines = componentInfos
    .filter((x) => x.kind === 'injectable')
    .map((x) => `  ${x.name},`)
  injectableLines.sort((a, b) => a.localeCompare(b))

  const lines: string[] = [
    '/* eslint-disable */',
    '',
    '// This file was automatically generated by nest-component-scan.',
    '',
    ...importLines,
    '',
    'export const SCANNED_CONTROLLERS = [',
    ...controllerLines,
    '];',
    '',
    'export const SCANNED_INJECTABLES = [',
    ...injectableLines,
    '];',
    '',
  ]

  return lines.join('\n')
}

export async function generateFile(input: {
  fileContents: string
  outFilePath: string
}): Promise<void> {
  const { fileContents, outFilePath } = input

  await fs.promises.writeFile(outFilePath, fileContents)

  console.log(`${new Date().toISOString()} ${outFilePath} generated.`)
}
